function translateTextToEn(str){
  if(!str || !/[\u0600-\u06FF]/.test(str)) return str;
  let out = str;
  for(const [fa,en] of FA_EN_PHRASES){
    if(!fa) continue;
    // Short labels: exact whole-string only (avoids mid-word damage like باز→Open inside بازگشت)
    if(fa.length <= 4){
      if(out === fa) out = en;
      continue;
    }
    if(out.indexOf(fa)!==-1) out = out.split(fa).join(en);
  }
  // Persian digits → Latin
  out = out.replace(/[۰-۹]/g, d => '0123456789'['۰۱۲۳۴۵۶۷۸۹'.indexOf(d)]);
  // Guarantee: no Persian letters remain in EN UI strings
  if(/[\u0600-\u06FF]/.test(out)){
    out = out.replace(/[\u0600-\u06FF]+/g, ' ').replace(/[‌‍]/g,'').replace(/\s{2,}/g,' ').trim();
  }
  return out;
}
function scrubPersianFromDom(root){
  if(!root) return;
  const skip = 'SCRIPT,STYLE,TEXTAREA,INPUT,CODE,PRE';
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node){
      const p = node.parentElement;
      if(!p) return NodeFilter.FILTER_REJECT;
      if(p.closest('[data-lang="en"]')) return NodeFilter.FILTER_REJECT;
      // Never scrub user-typed content in form fields; placeholders handled below
      if(p.closest(skip)) return NodeFilter.FILTER_REJECT;
      if(!/[\u0600-\u06FF]/.test(node.textContent||'')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes=[];
  while(walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(n=>{
    if(!n._faOrig) n._faOrig = n.textContent;
    n.textContent = translateTextToEn(n._faOrig);
  });
  root.querySelectorAll('input[placeholder],textarea[placeholder]').forEach(el=>{
    if(el.closest('[data-lang="en"]')) return;
    if(!el.dataset.faPh && /[\u0600-\u06FF]/.test(el.placeholder||'')) el.dataset.faPh = el.placeholder;
    const src = el.dataset.faPh || el.placeholder || '';
    el.placeholder = translateTextToEn(src);
  });
  root.querySelectorAll('[title],[aria-label]').forEach(el=>{
    if(el.closest('[data-lang="en"]')) return;
    ['title','aria-label'].forEach(attr=>{
      const v = el.getAttribute(attr);
      if(!v) return;
      const key = 'fa'+attr.replace('-','');
      if(/[\u0600-\u06FF]/.test(v) && !el.dataset[key]) el.dataset[key]=v;
      const src = el.dataset[key] || v;
      if(/[\u0600-\u06FF]/.test(src)) el.setAttribute(attr, translateTextToEn(src));
    });
  });
  // Final sweep: any remaining FA text nodes (e.g. after dynamic inject)
  const walker2 = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node){
      const p=node.parentElement;
      if(!p||p.closest(skip)) return NodeFilter.FILTER_REJECT;
      if(/[\u0600-\u06FF]/.test(node.textContent||'')) return NodeFilter.FILTER_ACCEPT;
      return NodeFilter.FILTER_REJECT;
    }
  });
  const more=[];
  while(walker2.nextNode()) more.push(walker2.currentNode);
  more.forEach(n=>{ n.textContent = translateTextToEn(n.textContent); });
}
function restorePersianDom(root){
  if(!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
    const n = walker.currentNode;
    if(n._faOrig) n.textContent = n._faOrig;
  }
  root.querySelectorAll('[data-fa-ph]').forEach(el=>{ el.placeholder = el.dataset.faPh; });
  root.querySelectorAll('[data-fatitle]').forEach(el=>{ if(el.dataset.fatitle) el.setAttribute('title', el.dataset.fatitle); });
  root.querySelectorAll('[data-faarialabel]').forEach(el=>{ if(el.dataset.faarialabel) el.setAttribute('aria-label', el.dataset.faarialabel); });
}

